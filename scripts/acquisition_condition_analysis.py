"""Phase 9: descriptive geometry-versus-embedding analysis for 50 m BlueBoat pairs.

Run from the repository root without loading or running any encoder:
    python -m scripts.acquisition_condition_analysis

Inputs (locally generated by the original dataset builder and encoder benchmarks):
    outputs/tables/positive_pair_metadata.csv
    outputs/embeddings/{resnet50,convnext_tiny,vit_b16,clip_vit_b32}_*
Outputs (isolated; no existing benchmark files are modified):
    outputs/analysis/acquisition_conditions/*.csv and *.png

Important: anchor side/ground-range refer to the *selected geocoded anchor*,
not to all contributing pixels of the final port+starboard sonar mosaic.
The 25 curated pairs are small and correlated. Results are descriptive only.

Input: outputs/tables/positive_pair_metadata.csv plus four sets of cached margins/retrieval CSVs.
Output: outputs/analysis/acquisition_conditions/: four PNGs and three CSVs.
Anchor side/range describe selected anchors, not every pixel of a mixed mosaic.
"""

import argparse
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
import numpy as np
import pandas as pd

from scripts.benchmark_comparison import ENCODERS, CONDITIONS, SURVEY_PAIRS

METADATA_FIELDS = (
    "pair", "patch_id", "heading_difference_deg", "look_difference_deg",
    "a_ground_range_m", "b_ground_range_m", "a_side", "b_side", "view_class",
)
PAIR_FIELDS = ("survey_pair", "pair_id")
VIEW_CLASSES = ("similar-view", "oblique-view", "opposite-view")
SIDES = ("port", "starboard")


def _read_csv(path, required, key):
    """Load required columns from a cached CSV, rejecting incomplete or duplicated keys."""
    if not path.is_file():
        raise FileNotFoundError(f"Missing input: {path}. Run the original 50 m dataset builder/benchmark first.")
    frame = pd.read_csv(path)
    missing = sorted(set(required) - set(frame.columns))
    if missing:
        raise ValueError(f"{path.name}: missing columns {missing}")
    if frame.duplicated(list(key)).any():
        raise ValueError(f"{path.name}: duplicate IDs {key}")
    return frame


def read_geometry(root):
    """Read actual positive-pair anchor metadata; never impute side/range."""
    metadata = _read_csv(
        Path(root) / "outputs/tables/positive_pair_metadata.csv",
        METADATA_FIELDS, ("pair", "patch_id"),
    ).copy()
    if len(metadata) != 25 or set(metadata["pair"]) != set(SURVEY_PAIRS):
        raise ValueError("Expected exactly 25 original positives in A-B, A-C and B-C")
    geometry = (
        "heading_difference_deg", "look_difference_deg",
        "a_ground_range_m", "b_ground_range_m",
    )
    if not np.isfinite(metadata[list(geometry)].to_numpy(dtype=float)).all():
        raise ValueError("Non-finite heading/look/range metadata; refusing to impute")
    if (metadata[["heading_difference_deg", "look_difference_deg"]] < 0).any().any():
        raise ValueError("Angle differences must be nonnegative")
    if (metadata[["heading_difference_deg", "look_difference_deg"]] > 180).any().any():
        raise ValueError("Angle differences must be <=180 degrees")
    if (metadata[["a_ground_range_m", "b_ground_range_m"]] < 0).any().any():
        raise ValueError("Ground-range distances must be nonnegative")
    if not metadata["a_side"].isin(SIDES).all() or not metadata["b_side"].isin(SIDES).all():
        raise ValueError("Expected anchor-side values port/starboard")
    if not metadata["view_class"].isin(VIEW_CLASSES).all():
        raise ValueError("Unexpected view classes in positive metadata")

    metadata = metadata.rename(columns={"pair": "survey_pair", "patch_id": "pair_id"})
    metadata["anchor_side_pair"] = metadata["a_side"] + "→" + metadata["b_side"]
    metadata["mean_anchor_ground_range_m"] = (
        metadata["a_ground_range_m"] + metadata["b_ground_range_m"]
    ) / 2
    metadata["anchor_ground_range_difference_m"] = (
        metadata["a_ground_range_m"] - metadata["b_ground_range_m"]
    ).abs()
    if "coverage_a" in metadata.columns and "coverage_b" in metadata.columns:
        if not np.isfinite(metadata[["coverage_a", "coverage_b"]].to_numpy(float)).all():
            raise ValueError("Non-finite coverage metadata")
    return metadata


def create_analysis_table(root):
    """Join matched-null scores and directional retrieval to all 25 anchor pairs."""
    root = Path(root)
    metadata = read_geometry(root)
    frames = []
    geometry_ids = set(map(tuple, metadata[list(PAIR_FIELDS)].itertuples(index=False, name=None)))

    for stem, name in ENCODERS:
        source = root / "outputs/embeddings"
        margins = _read_csv(
            source / f"{stem}_matched_null_margins.csv",
            (*PAIR_FIELDS, "condition", "margin", "positive_cosine", "requires_review"),
            (*PAIR_FIELDS, "condition"),
        )
        queries = _read_csv(
            source / f"{stem}_retrieval_queries.csv",
            (*PAIR_FIELDS[:1], "condition", "direction", "query_patch_id",
             "expected_recall_at_1", "expected_recall_at_3", "tie_count"),
            ("survey_pair", "condition", "direction", "query_patch_id"),
        )
        if set(margins["condition"]) != set(CONDITIONS) or set(queries["condition"]) != set(CONDITIONS):
            raise ValueError(f"{stem}: SONAR/MASK-ONLY conditions are incomplete")
        for condition in CONDITIONS:
            ids = set(map(tuple, margins.loc[
                margins["condition"] == condition, list(PAIR_FIELDS)
            ].itertuples(index=False, name=None)))
            if ids != geometry_ids:
                raise ValueError(f"{stem}/{condition}: margins do not match positive metadata IDs")
        if not np.isfinite(margins[["margin", "positive_cosine"]].to_numpy(float)).all():
            raise ValueError(f"{stem}: non-finite matched-null metrics")
        if not np.isfinite(queries[["expected_recall_at_1", "expected_recall_at_3"]].to_numpy(float)).all():
            raise ValueError(f"{stem}: non-finite retrieval credits")

        q = queries.groupby(
            ["survey_pair", "query_patch_id", "condition"], as_index=False
        ).agg(
            n_directions=("direction", "nunique"),
            query_count=("direction", "size"),
            bidirectional_recall_at_1=("expected_recall_at_1", "mean"),
            bidirectional_recall_at_3=("expected_recall_at_3", "mean"),
        ).rename(columns={"query_patch_id": "pair_id"})
        if len(q) != 50 or not ((q["n_directions"] == 2) & (q["query_count"] == 2)).all():
            raise ValueError(f"{stem}: exactly two directional queries per positive pair required")
        joint = margins.merge(metadata, on=list(PAIR_FIELDS), how="left",
                              validate="many_to_one", indicator=True)
        if not (joint["_merge"] == "both").all() or len(joint) != 50:
            raise ValueError(f"{stem}: cannot uniquely join margins to positive geometry")
        joint = joint.drop(columns="_merge")
        joint = joint.merge(q, on=["survey_pair", "pair_id", "condition"],
                            how="left", validate="one_to_one", indicator=True)
        if not (joint["_merge"] == "both").all() or len(joint) != 50:
            raise ValueError(f"{stem}: cannot uniquely join directional retrieval")
        joint = joint.drop(columns="_merge")
        joint.insert(0, "encoder", name)
        joint.insert(1, "encoder_stem", stem)
        frames.append(joint)
    return pd.concat(frames, ignore_index=True)


def make_strata_table(data):
    """Summarize margins and retrieval by survey pair, viewpoint and selected anchor sides."""
    frames = []
    for dimension, column in (
        ("view_class", "view_class"),
        ("anchor_side_pair", "anchor_side_pair"),
        ("survey_pair", "survey_pair"),
    ):
        grouped = data.groupby(
            ["encoder", "encoder_stem", "condition", column],
            dropna=False, sort=True, as_index=False,
        ).agg(
            n_positive_pairs=("pair_id", "size"),
            mean_margin=("margin", "mean"),
            median_margin=("margin", "median"),
            positive_margin_fraction=("margin", lambda x: float((x > 0).mean())),
            mean_bidirectional_recall_at_1=("bidirectional_recall_at_1", "mean"),
            mean_bidirectional_recall_at_3=("bidirectional_recall_at_3", "mean"),
        )
        grouped["stratification"] = dimension
        grouped["stratum"] = grouped[column].astype(str)
        frames.append(grouped.drop(columns=column))
    return pd.concat(frames, ignore_index=True)


def _scatter_figure(data, columns, title, descriptions, destination):
    """Four models x two covariates, SONAR only; color indicates survey pair."""
    fig, axes = plt.subplots(4, 2, figsize=(13, 13), sharey=True, squeeze=False)
    subset = data.loc[data["condition"] == "sonar"]
    colors = dict(zip(SURVEY_PAIRS, ("tab:blue", "tab:orange", "tab:green")))
    ymin, ymax = subset["margin"].min(), subset["margin"].max()
    span = max(0.1, float(ymax - ymin))
    for i, (stem, name) in enumerate(ENCODERS):
        frame = subset.loc[subset["encoder_stem"] == stem]
        for j, (col, description) in enumerate(zip(columns, descriptions)):
            ax = axes[i, j]
            for pair in SURVEY_PAIRS:
                obs = frame.loc[frame["survey_pair"] == pair]
                ax.scatter(obs[col], obs["margin"], s=38, alpha=0.82,
                           color=colors[pair], label=pair.replace("pass_", "").upper())
            ax.axhline(0, linestyle="--", color="0.5", linewidth=1)
            ax.set_ylim(ymin - 0.12*span, ymax + 0.12*span)
            ax.set_title(f"{name} | {description}", fontsize=11)
            ax.set_xlabel(description)
            if j == 0:
                ax.set_ylabel("Matched-negative margin")
            ax.grid(alpha=0.17)
    handles, labels = axes[0, 0].get_legend_handles_labels()
    fig.legend(handles, labels, ncol=3, loc="upper center", bbox_to_anchor=(0.5, 0.96))
    fig.suptitle(title, fontsize=15)
    fig.text(0.02, 0.012,
             "n=25 correlated positive pairs per model; anchor-derived geometry; descriptive only.",
             fontsize=9, color="dimgray")
    fig.tight_layout(rect=(0, 0.035, 1, 0.92), h_pad=2.2, w_pad=2.1)
    destination.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(destination, dpi=170, bbox_inches="tight")
    plt.close(fig)


def _side_figure(data, destination):
    """Compare margins across selected anchor sides, not exclusive pixel sides."""
    side_pairs = ("port→port", "port→starboard", "starboard→port", "starboard→starboard")
    colors = ("tab:blue", "tab:orange", "tab:green", "tab:red")
    labels = (
        "P→P = port → port",
        "P→S = port → starboard",
        "S→P = starboard → port",
        "S→S = starboard → starboard",
    )
    fig, axes = plt.subplots(4, 2, figsize=(14, 14), sharey=True, squeeze=False)
    ymin, ymax = data["margin"].min(), data["margin"].max()
    span = max(0.1, float(ymax - ymin))
    for i, (stem, name) in enumerate(ENCODERS):
        for j, condition in enumerate(CONDITIONS):
            ax = axes[i, j]
            subset = data.loc[(data["encoder_stem"] == stem)
                              & (data["condition"] == condition)]
            for k, (side_pair, color) in enumerate(zip(side_pairs, colors)):
                values = subset.loc[subset["anchor_side_pair"] == side_pair, "margin"].to_numpy(float)
                if not values.size:
                    continue
                dx = np.linspace(-0.14, 0.14, len(values))
                ax.scatter(k + dx, values, s=32, alpha=0.75, color=color)
                ax.plot([k - 0.22, k + 0.22], [values.mean()]*2,
                        linewidth=2, color="black")
                ax.text(k, ymax + 0.075*span, f"n={len(values)}",
                        ha="center", fontsize=8)
            ax.axhline(0, color="0.5", linestyle="--", linewidth=1)
            ax.set_ylim(ymin - 0.12*span, ymax + 0.17*span)
            ax.set_xticks(range(4), ("P→P", "P→S", "S→P", "S→S"))
            ax.set_title(f"{name} | {condition.upper()}")
            if j == 0:
                ax.set_ylabel("Matched-negative margin")
            ax.grid(alpha=0.18)

    legend_handles = [
        Line2D([0], [0], linestyle="none", marker="o", markersize=7,
               markerfacecolor=color, markeredgecolor="none", label=label)
        for color, label in zip(colors, labels)
    ]
    fig.suptitle("Matched margins by selected anchor side", fontsize=14, y=0.995)
    fig.legend(handles=legend_handles, ncol=2, loc="upper center",
               bbox_to_anchor=(0.5, 0.974), fontsize=9, frameon=True)
    fig.text(
        0.02, 0.014,
        "P = port (left); S = starboard (right); n = positive pairs. "
        "Anchor side does not describe every pixel in a geocoded mosaic.",
        fontsize=9, color="dimgray",
    )
    fig.tight_layout(rect=(0, 0.04, 1, 0.89), h_pad=2.0)
    destination.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(destination, dpi=170, bbox_inches="tight")
    plt.close(fig)



def make_delta_table(data):
    """Pair SONAR and MASK-ONLY margins for every encoder and positive patch."""
    identifiers = ["encoder_stem", "survey_pair", "pair_id"]
    if data.duplicated(identifiers + ["condition"]).any():
        raise ValueError("Duplicate encoder/pair/condition observations")
    sonar = data.loc[data["condition"] == "sonar"].copy()
    mask = data.loc[data["condition"] == "mask-only", identifiers + ["margin"]].rename(
        columns={"margin": "margin_mask_only"}
    )
    # The outer join exposes missing partners: never compare unrelated positive IDs.
    joined = sonar.merge(mask, on=identifiers, how="outer",
                         validate="one_to_one", indicator=True)
    if (not (joined["_merge"] == "both").all()
            or len(joined) != len(ENCODERS) * 25
            or not np.isfinite(joined[["margin", "margin_mask_only"]].to_numpy(float)).all()):
        raise ValueError("SONAR and MASK-ONLY margins must align across all 25 pairs per encoder")
    joined = joined.drop(columns="_merge")
    joined = joined.rename(columns={"margin": "margin_sonar"})
    joined["delta_margin_sonar_minus_mask"] = (
        joined["margin_sonar"] - joined["margin_mask_only"]
    )
    return joined.sort_values(identifiers).reset_index(drop=True)


def _delta_figure(deltas, destination):
    """Single 4x2 figure; one row per encoder, paired margin difference on y."""
    fig, axes = plt.subplots(4, 2, figsize=(13.5, 13.5), sharey=True, squeeze=False)
    colors = dict(zip(SURVEY_PAIRS, ("tab:blue", "tab:orange", "tab:green")))
    delta_col = "delta_margin_sonar_minus_mask"
    ymin, ymax = float(deltas[delta_col].min()), float(deltas[delta_col].max())
    span = max(0.1, ymax - ymin)
    lower = min(ymin, 0.0) - 0.11 * span
    upper = max(ymax, 0.0) + 0.11 * span
    for i, (stem, model_name) in enumerate(ENCODERS):
        frame = deltas.loc[deltas["encoder_stem"] == stem]
        if len(frame) != 25:
            raise ValueError(f"{stem}: expected 25 paired SONAR/MASK-ONLY observations")
        for j, (column, xlabel) in enumerate((
            ("look_difference_deg", "Look-azimuth difference (degrees)"),
            ("anchor_ground_range_difference_m", "Absolute anchor ground-range difference (m)"),
        )):
            ax = axes[i, j]
            for pair in SURVEY_PAIRS:
                points = frame.loc[frame["survey_pair"] == pair]
                ax.scatter(points[column], points[delta_col], s=39, alpha=0.82,
                           color=colors[pair], label=pair.replace("pass_", "").upper())
            ax.axhline(0, color="0.4", linestyle="--", linewidth=1)
            ax.set_ylim(lower, upper)
            ax.set_title(f"{model_name} | {xlabel}", fontsize=11)
            ax.set_xlabel(xlabel)
            if j == 0:
                ax.set_ylabel("Δ margin (SONAR − MASK-ONLY)")
            ax.grid(alpha=0.18)
    handles, labels = axes[0, 0].get_legend_handles_labels()
    fig.suptitle("Matched-margin advantage of SONAR over MASK-ONLY", fontsize=15)
    fig.legend(handles, labels, ncol=3, loc="upper center", bbox_to_anchor=(0.5, 0.96))
    fig.text(
        0.02, 0.012,
        "Δ > 0: SONAR has a higher matched-negative margin; Δ < 0: MASK-ONLY has a higher margin. "
        "n=25 correlated pairs/model; descriptive only.",
        fontsize=9, color="dimgray",
    )
    fig.tight_layout(rect=(0, 0.04, 1, 0.92), h_pad=2.2, w_pad=2.0)
    destination.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(destination, dpi=170, bbox_inches="tight")
    plt.close(fig)



def generate(root, output_dir):
    """Write acquisition-condition tables and charts from already cached metrics."""
    data = create_analysis_table(root)
    summary = make_strata_table(data)
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    data.to_csv(output / "acquisition_positive_pair_metrics.csv", index=False)
    summary.to_csv(output / "acquisition_strata_summary.csv", index=False)

    _scatter_figure(
        data,
        columns=("heading_difference_deg", "look_difference_deg"),
        title="SONAR margin vs acquisition orientation",
        descriptions=("Heading difference (degrees)", "Look-azimuth difference (degrees)"),
        destination=output / "acquisition_heading_look_vs_margin.png",
    )
    _scatter_figure(
        data,
        columns=("mean_anchor_ground_range_m", "anchor_ground_range_difference_m"),
        title="SONAR margin vs anchor ground range",
        descriptions=("Mean anchor ground range (m)", "Absolute anchor range difference (m)"),
        destination=output / "acquisition_anchor_range_vs_margin.png",
    )
    _side_figure(data, output / "acquisition_anchor_side_vs_margin.png")
    deltas = make_delta_table(data)
    deltas.to_csv(output / "acquisition_sonar_mask_margin_delta.csv", index=False)
    _delta_figure(deltas, output / "acquisition_sonar_mask_delta_vs_geometry.png")
    return data, summary


def main():
    """Parse output-directory options and run only the descriptive analysis."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output-dir", type=Path, default=None)
    args = parser.parse_args()
    output = args.output_dir or args.root / "outputs/analysis/acquisition_conditions"
    generate(args.root, output)


if __name__ == "__main__":
    main()
